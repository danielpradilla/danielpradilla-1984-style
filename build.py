#!/usr/bin/env python3
"""Build icons/*.svg and pixels.css from pixels.txt. Run after editing any bitmap.

pixels.txt blocks:  `icon NAME` -> icons/NAME.svg     `css NAME` -> --NAME custom property
Pixels: '#' black, 'o' white, '.' transparent. Blocks end at a blank line. ';' starts a comment.
"""
import pathlib
import re
import urllib.parse

ROOT = pathlib.Path(__file__).parent
FILL = {"#": "#000", "o": "#fff"}


def parse(text):
    blocks, cur = [], None
    for line in text.splitlines():
        if not line.strip() or line.startswith(";"):
            cur = None
        elif line.startswith(("icon ", "css ")):
            kind, name = line.split()
            cur = (kind, name, [])
            blocks.append(cur)
        else:
            assert cur, f"pixel row outside a block: {line!r}"
            cur[2].append(line.rstrip())
    return blocks


def svg(name, rows, scale=1):
    w, h = len(rows[0]), len(rows)
    for y, row in enumerate(rows):
        assert len(row) == w, f"{name}: row {y} is {len(row)} wide, expected {w}"
        assert set(row) <= set(".#o"), f"{name}: row {y} has characters other than . # o"
    paths = dict.fromkeys(FILL, "")
    for y, row in enumerate(rows):
        for m in re.finditer(r"#+|o+", row):
            n = len(m.group())
            paths[m.group()[0]] += f"M{m.start()} {y}h{n}v1h-{n}z"
    body = "".join(f'<path fill="{FILL[c]}" d="{d}"/>' for c, d in paths.items() if d)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w * scale}" height="{h * scale}" '
            f'viewBox="0 0 {w} {h}" shape-rendering="crispEdges">{body}</svg>')


def main():
    (ROOT / "icons").mkdir(exist_ok=True)
    for old in (ROOT / "icons").glob("*.svg"):  # drop icons removed from pixels.txt
        old.unlink()
    props = []
    for kind, name, rows in parse((ROOT / "pixels.txt").read_text()):
        if kind == "icon":
            (ROOT / "icons" / f"{name}.svg").write_text(svg(name, rows) + "\n")
        else:
            # Cursors ignore CSS zoom, so each one also gets a double-size copy for the 2x scale.
            for suffix, scale in [("", 1), ("-2x", 2)] if name.startswith("cur-") else [("", 1)]:
                uri = urllib.parse.quote(svg(name, rows, scale).replace('"', "'"), safe=" '=:/-.,")
                props.append(f'  --{name}{suffix}: url("data:image/svg+xml,{uri}");')
    (ROOT / "pixels.css").write_text(
        "/* Generated by build.py from pixels.txt. Do not edit by hand. */\n:root {\n"
        + "\n".join(props) + "\n}\n")
    print(f"{len(props)} css bitmaps, {len(list((ROOT / 'icons').glob('*.svg')))} icons")


if __name__ == "__main__":
    main()
